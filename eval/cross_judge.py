"""Cross-judge bias check — rescore an existing eval run with a second model.

LLM-as-judge has a known same-family bias (a judge tends to prefer responses
generated by models in its own family). For the bitext27 reports the judge
is `gpt-4o-mini` — the same model that produced the draft. This script
re-judges every final_draft in an existing results JSON with a different
model (default: `gpt-4o`), then reports:

  - per-ticket score from both judges (1–5 LLM-judge rubric)
  - Pearson correlation between the two judges' scores
  - quadratic-weighted Cohen's kappa (ordinal agreement)

Run:

    LLM_PROVIDER=openai OPENAI_MODEL=gpt-4o-mini \\
      python -m eval.cross_judge \\
        --input eval/results_bitext27_v4.json \\
        --judge-model gpt-4o \\
        --output eval/cross_judge_results.json

Honest scope: this only mitigates *size* bias within the OpenAI family. A
fully different-family judge (Anthropic Claude / Google Gemini) would be a
stronger signal — deferred until a non-OpenAI key is available.
"""

from __future__ import annotations

import argparse
import asyncio
import json
import os
import sys
from pathlib import Path
from typing import Any

from dotenv import load_dotenv
from openai import AsyncOpenAI

# Load .env at import so the harness's OPENAI_API_KEY is visible.
load_dotenv(Path(__file__).parent.parent / ".env")

# Local imports (no graph deps) — put after dotenv so module-level reads of
# API keys see the populated env.
_REPO_ROOT = Path(__file__).parent.parent
if str(_REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(_REPO_ROOT))

from eval.evaluators import QUALITY_RUBRIC  # noqa: E402
from eval.stats import cohen_quadratic_kappa, pearson  # noqa: E402


async def _judge_one(
    client: AsyncOpenAI,
    model: str,
    customer_message: str,
    draft: str,
) -> dict[str, Any]:
    """One judge call. Mirrors eval/evaluators.response_quality_single() shape
    but lets the caller pin a specific model id (so we can swap judges)."""
    resp = await client.chat.completions.create(
        model=model,
        messages=[
            {"role": "system", "content": QUALITY_RUBRIC},
            {
                "role": "user",
                "content": json.dumps(
                    {"customer_message": customer_message, "agent_reply": draft},
                    ensure_ascii=False,
                ),
            },
        ],
        response_format={"type": "json_object"},
        temperature=0.1,
    )
    content = (resp.choices[0].message.content or "").strip()
    return json.loads(content)


async def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--input",
        required=True,
        help="Path to an existing eval results JSON "
        "(e.g. eval/results_bitext27_v4.json).",
    )
    parser.add_argument(
        "--judge-model",
        default="gpt-4o",
        help="Model id used as the alternative judge (default: gpt-4o).",
    )
    parser.add_argument(
        "--primary-judge-model",
        default=None,
        help=(
            "Model id that produced the primary scores in the input JSON. "
            "Honest labelling only — does not affect computation. If omitted, "
            "falls back to the current LLM_PROVIDER env (not always correct "
            "if you've changed the env since the eval; ultrareview merged_bug_013)."
        ),
    )
    parser.add_argument(
        "--output",
        default=None,
        help="Output JSON path. Default: eval/cross_judge_<input stem>.json",
    )
    args = parser.parse_args()

    input_path = Path(args.input)
    if not input_path.exists():  # noqa: ASYNC240
        print(f"ERROR: input file not found: {input_path}")
        return 1
    output_path = (
        Path(args.output)
        if args.output
        else input_path.parent / f"cross_judge_{input_path.stem}.json"
    )

    with open(input_path, encoding="utf-8") as f:  # noqa: ASYNC230
        data = json.load(f)

    # The original judge's per-ticket scores live in response_quality_details.
    primary_judge_per_ticket = data.get("response_quality_details", {}).get(
        "per_ticket", []
    )
    # Explicit flag wins; otherwise fall back to current-env best-guess and
    # emit a warning. The current-env fallback is correct-by-coincidence
    # only when the operator hasn't changed env between the eval run and
    # this script (ultrareview merged_bug_013).
    if args.primary_judge_model:
        primary_judge_model = args.primary_judge_model
    else:
        primary_judge_model = (
            os.environ.get("OPENAI_MODEL", "gpt-4o-mini")
            if os.environ.get("LLM_PROVIDER", "").lower() == "openai"
            else os.environ.get("OPENROUTER_MODEL", "deepseek/deepseek-chat")
        )
        print(
            f"[cross_judge] --primary-judge-model not provided; guessing "
            f"{primary_judge_model!r} from current env. Pass --primary-judge-model "
            f"explicitly for honest labelling."
        )
    primary_by_ticket = {p["ticket_id"]: p for p in primary_judge_per_ticket}

    # Re-judge every per-ticket entry that has a final_draft we can score.
    # The original JSON's per_ticket array carries ticket metadata but NOT
    # the final_draft text; we need it. Look it up by ticket_id by reading
    # the rep files... actually the bitext27 JSON includes per-ticket entries
    # with `description` but not draft text. Workaround: load the dataset and
    # match by ticket_id to get customer_message; the draft is in the response
    # quality block as "draft"-shaped per_ticket entries... actually no, only
    # the score+reason are there. We need to re-run to get drafts.
    #
    # Pragmatic alternative: the bitext27 JSON DOES include per_ticket rows
    # with intent + description; the final_draft is NOT serialized. So this
    # cross-judge implementation needs the draft text. Two options:
    #   (a) Extend run_experiments.py to also write per-ticket `final_draft`
    #       into per_ticket (small JSON growth).
    #   (b) Re-run the eval just to capture drafts.
    # I take option (a) in a follow-up edit (this commit) — see
    # eval/run_experiments.py per_ticket dict.
    if not primary_judge_per_ticket:
        print(
            "ERROR: input JSON has no response_quality_details — was this run "
            "live (with the judge enabled)?"
        )
        return 1

    drafts_by_ticket: dict[str, dict[str, str]] = {}
    truncated_input_seen = False
    for row in data.get("per_ticket", []):
        ticket_id = row.get("ticket_id")
        draft = row.get("final_draft")
        # Prefer the FULL customer_message field added by run_experiments
        # post-ultrareview merged_bug_013. Older result JSONs only carried
        # customer_message_snippet (first 240 chars) — fall back to that
        # but warn loudly: scoring a 240-char snippet against the primary
        # judge that saw the full text conflates judge bias with input
        # asymmetry, so any kappa from such a run is methodologically suspect.
        msg = row.get("customer_message")
        if msg is None:
            msg = row.get("customer_message_snippet", "")
            if msg:
                truncated_input_seen = True
        if ticket_id and draft:
            drafts_by_ticket[ticket_id] = {
                "customer_message": msg,
                "final_draft": draft,
            }

    if truncated_input_seen:
        print(
            "[cross_judge] WARNING: input JSON only carries customer_message_snippet "
            "(first 240 chars), not full customer_message. The bias metrics below "
            "may be affected by input-truncation asymmetry — re-run the underlying "
            "eval on post-ultrareview run_experiments.py and retry for clean numbers."
        )

    if not drafts_by_ticket:
        print(
            "ERROR: per_ticket rows do not carry final_draft text. Re-run the "
            "eval on the post-Commit-4 harness so the draft is serialised, "
            "then retry."
        )
        return 1

    client = AsyncOpenAI(api_key=os.environ.get("OPENAI_API_KEY", ""))
    print(
        f"[cross_judge] primary judge: {primary_judge_model} "
        f"(scores from {input_path.name})"
    )
    print(f"[cross_judge] secondary judge: {args.judge_model}")
    print(f"[cross_judge] scoring {len(drafts_by_ticket)} drafts...\n")

    per_ticket_out: list[dict[str, Any]] = []
    primary_scores: list[int] = []
    secondary_scores: list[int] = []

    for ticket_id, payload in drafts_by_ticket.items():
        primary_row = primary_by_ticket.get(ticket_id, {})
        primary_score = primary_row.get("score")
        if primary_score is None:
            continue
        try:
            secondary = await _judge_one(
                client,
                args.judge_model,
                payload["customer_message"],
                payload["final_draft"],
            )
        except Exception as exc:  # noqa: BLE001
            per_ticket_out.append(
                {
                    "ticket_id": ticket_id,
                    "primary_score": primary_score,
                    "secondary_score": None,
                    "secondary_reason": f"judge error: {exc}",
                }
            )
            continue
        sec_score = secondary.get("score")
        per_ticket_out.append(
            {
                "ticket_id": ticket_id,
                "primary_score": primary_score,
                "primary_reason": primary_row.get("reason", ""),
                "secondary_score": sec_score,
                "secondary_reason": secondary.get("reason", ""),
            }
        )
        if isinstance(sec_score, int) and 1 <= sec_score <= 5:
            primary_scores.append(int(primary_score))
            secondary_scores.append(sec_score)
        print(
            f"  {ticket_id}  primary={primary_score}  "
            f"secondary={sec_score}"
        )

    corr = pearson(
        [float(s) for s in primary_scores],
        [float(s) for s in secondary_scores],
    )
    kappa = cohen_quadratic_kappa(primary_scores, secondary_scores, k_max=5)

    summary = {
        "input_file": str(input_path),
        "primary_judge": primary_judge_model,
        "secondary_judge": args.judge_model,
        "scored_count": len(primary_scores),
        "pearson_correlation": round(corr, 4),
        "cohen_quadratic_kappa": round(kappa, 4),
        "per_ticket": per_ticket_out,
        "interpretation": (
            "kappa < 0.4 = weak agreement (judges disagree often); "
            "0.4–0.6 = moderate; 0.6–0.8 = substantial; > 0.8 = near-identical. "
            "Both judges are OpenAI gpt-* models, so high agreement is partly "
            "family bias — see eval/METHODOLOGY.md."
        ),
    }

    with open(output_path, "w", encoding="utf-8") as f:  # noqa: ASYNC230
        json.dump(summary, f, indent=2)
    print(
        f"\n[cross_judge] pearson r = {corr:.3f}   "
        f"quadratic kappa = {kappa:.3f}   "
        f"(n = {len(primary_scores)})"
    )
    print(f"[cross_judge] written -> {output_path}")
    return 0


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
